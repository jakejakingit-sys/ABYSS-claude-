#!/usr/bin/env python3
"""assets/player/*.txt ASCII pixel art -> src/assets.c (indexed, 0 = transparent)"""
PAL = {'.':0,'o':13,'s':6,'c':7,'r':8}
order = ['idle','run1','run2','jump','fall']
o = ['/* GENERATED by tools/mkassets.py - do not edit */','#include "assets.h"','const uint8_t PLAYER_FRAMES[5][2 + 10 * 14] = {']
for n in order:
    rows = open(f'assets/player/{n}.txt').read().split()
    assert len(rows) == 14 and all(len(r) == 10 for r in rows), f'{n}: must be 10x14 (got {len(rows)} rows)'
    o.append('  {10,14,' + ','.join(str(PAL[c]) for r in rows for c in r) + '},')
o.append('};')
open('src/assets.c','w').write('\n'.join(o)+'\n'); print('assets ok')
