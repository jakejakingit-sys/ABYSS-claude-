#!/usr/bin/env python3
"""levels/world*/NN_name.txt -> src/level_data.c  (1 byte/tile, const => archive/flash, never copied to RAM)"""
import glob, sys
CH = {'.':0,'#':1,'=':2,'^':3,'H':4,'$':5,'C':6,'E':7,'S':0}
files = sorted(glob.glob('levels/world*/*.txt'))
out = ['/* GENERATED by tools/mklevels.py - do not edit */', '#include "level.h"']
defs = []
for i, f in enumerate(files):
    L = open(f).read().splitlines()
    name = L[0].split(':', 1)[1].strip(); world = int(L[1].split(':', 1)[1])
    rows = L[2:]; h = len(rows); w = len(rows[0]); spawn = None
    assert all(len(r) == w for r in rows), f"{f}: ragged rows"
    assert w <= 64 and h <= 15, f"{f}: too big"
    data = []
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == 'S': spawn = (x, y)
            data.append(CH[c])
    assert spawn, f"{f}: no spawn"
    out.append(f'static const uint8_t L{i}[{len(data)}] = {{' + ','.join(map(str, data)) + '};')
    defs.append(f'  {{{world},{w},{h},{spawn[0]},{spawn[1]},L{i},"{name}"}}')
out.append(f'const LevelDef LEVELS[LEVELS_IMPLEMENTED] = {{\n' + ',\n'.join(defs) + '\n};')
assert len(files) == 2, "update LEVELS_IMPLEMENTED in include/abyss.h"
open('src/level_data.c', 'w').write('\n'.join(out) + '\n')
print(f'{len(files)} levels written')
